// OpenWALDO site — small shared behaviors. No dependencies.

// Mobile nav toggle
const menuBtn = document.getElementById('menu-btn');
if (menuBtn) {
  menuBtn.addEventListener('click', () => {
    document.querySelector('nav.links').classList.toggle('open');
  });
}

// Scroll-reveal
const io = new IntersectionObserver((entries) => {
  for (const e of entries) {
    if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
  }
}, { threshold: 0.12 });
document.querySelectorAll('.reveal').forEach((el) => io.observe(el));

// Corpus counter: fill the front-page stats strip from assets/stats.json
// (regenerated by tools/corpus-stats.py against a waldo-index checkout).
// Numbers count up when the strip scrolls into view; the license bar is a
// token-share spectrum built from the same data.
const statsBox = document.querySelector('[data-stats]');
if (statsBox) {
  const reduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
  const NUM = [[1e12, 'T'], [1e9, 'B'], [1e6, 'M'], [1e3, 'K'], [1, '']];
  const SIZE = [[1e12, ' TB'], [1e9, ' GB'], [1e6, ' MB'], [1e3, ' KB'], [1, ' B']];
  const split = (n, units) => {
    for (const [v, u] of units) if (n >= v || v === 1) return [n / v, u];
  };
  const fmt = (x, target) =>
    target >= 100 || Number.isInteger(target)
      ? String(Math.round(x))
      : x.toFixed(1).replace(/\.0$/, target >= 10 ? '' : '.0');

  const pending = [];
  const setStat = (key, n, units, title) => {
    const box = statsBox.querySelector(`[data-stat="${key}"]`);
    if (!box) return;
    const [value, unit] = units ? split(n, units) : [n, ''];
    box.querySelector('.u').textContent = unit;
    if (title) box.title = title;
    const v = box.querySelector('.v');
    if (reduced) { v.textContent = fmt(value, value); return; }
    pending.push({ el: v, value });
  };

  const runCountUp = () => {
    const t0 = performance.now(), dur = 1600;
    const tick = (t) => {
      const p = Math.min((t - t0) / dur, 1);
      const ease = 1 - Math.pow(1 - p, 4);
      for (const s of pending) s.el.textContent = fmt(s.value * ease, s.value);
      if (p < 1) requestAnimationFrame(tick);
    };
    requestAnimationFrame(tick);
  };

  const PALETTE = ['#ff4a3d', '#f4eddd', '#ff8a5c', '#8fa0bd', '#ffb454',
                   '#d92e23', '#c9b8a0', '#7d8aa5', '#ffd9d5', '#58627a'];

  fetch('assets/stats.json')
    .then((r) => (r.ok ? r.json() : null))
    .then((s) => {
      if (!s) return;
      const licenses = Object.entries(s.licenses || {})
        .sort((a, b) => b[1].tokens - a[1].tokens);

      setStat('tokens', s.tokens, NUM, s.tokens.toLocaleString() + ' tokens');
      setStat('docs', s.docs, NUM, s.docs.toLocaleString() + ' documents');
      setStat('bytes', s.bytes, SIZE,
        s.bytes.toLocaleString() + ' bytes across ' + s.shards + ' shard(s)');
      setStat('licenses', licenses.length, null,
        licenses.map(([name]) => name).join(', '));

      const bar = statsBox.querySelector('[data-stat="bar"]');
      const legend = statsBox.querySelector('[data-stat="legend"]');
      if (bar && legend && s.tokens > 0) {
        licenses.forEach(([name, info], i) => {
          const pct = (info.tokens / s.tokens) * 100;
          const pctLabel = pct >= 10 ? Math.round(pct) : pct >= 1 ? pct.toFixed(1) : '<1';
          const seg = document.createElement('span');
          seg.style.flexGrow = info.tokens;
          seg.style.background = PALETTE[i % PALETTE.length];
          seg.title = name + ' — ' + pctLabel + '% · ' +
            info.tokens.toLocaleString() + ' tokens';
          bar.appendChild(seg);
          const chip = document.createElement('span');
          chip.className = 'chip';
          chip.innerHTML = '<i style="background:' + PALETTE[i % PALETTE.length] +
            '"></i><b>' + name + '</b> ' + pctLabel + '%';
          legend.appendChild(chip);
        });
      }

      const note = statsBox.querySelector('[data-stat="note"]');
      if (note) {
        const when = (s.generated || '').slice(0, 10);
        note.textContent = (s.index_commit ? 'waldo-index@' + s.index_commit : 'the public index') +
          (when ? ' · ' + when : '') + ' · verifiable shard by shard ↗';
      }

      if (!reduced && pending.length) {
        const io2 = new IntersectionObserver((entries) => {
          if (entries.some((e) => e.isIntersecting)) { io2.disconnect(); runCountUp(); }
        }, { threshold: 0.35 });
        io2.observe(statsBox);
      }
    })
    .catch(() => {});
}

// Hero: cycle a glow across the W-A-L-D-O letters
const letters = document.querySelectorAll('h1.title .k');
if (letters.length && !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
  let i = 0;
  setInterval(() => {
    letters.forEach((l) => l.classList.remove('lit'));
    letters[i % letters.length].classList.add('lit');
    i++;
  }, 900);
}
