// OpenWALDO site — small shared behaviors. No dependencies.

// Mobile nav toggle
const menuBtn = document.getElementById('menu-btn');
if (menuBtn) {
  menuBtn.addEventListener('click', () => {
    document.querySelector('nav.links').classList.toggle('open');
  });
}

// Scroll-reveal
const io = new IntersectionObserver((entries) => {
  for (const e of entries) {
    if (e.isIntersecting) { e.target.classList.add('in'); io.unobserve(e.target); }
  }
}, { threshold: 0.12 });
document.querySelectorAll('.reveal').forEach((el) => io.observe(el));

// Corpus counter: fill the front-page stats strip from assets/stats.json
// (regenerated by tools/corpus-stats.py against a waldo-index checkout)
const statsBox = document.querySelector('[data-stats]');
if (statsBox) {
  const put = (key, value, title) => {
    const el = statsBox.querySelector(`[data-stat="${key}"]`);
    if (el) { el.textContent = value; if (title) el.title = title; }
  };
  const num = (n) => {
    for (const [v, u] of [[1e12, 'T'], [1e9, 'B'], [1e6, 'M'], [1e3, 'K']]) {
      if (n >= v) {
        const x = n / v;
        return (x >= 100 ? Math.round(x) : x.toFixed(1).replace(/\.0$/, '')) + u;
      }
    }
    return String(n);
  };
  const size = (n) => {
    for (const [v, u] of [[1e12, 'TB'], [1e9, 'GB'], [1e6, 'MB'], [1e3, 'KB']]) {
      if (n >= v) {
        const x = n / v;
        return (x >= 100 ? Math.round(x) : x.toFixed(1).replace(/\.0$/, '')) + ' ' + u;
      }
    }
    return n + ' B';
  };
  fetch('assets/stats.json')
    .then((r) => (r.ok ? r.json() : null))
    .then((s) => {
      if (!s) return;
      const licenses = Object.keys(s.licenses || {});
      put('tokens', num(s.tokens), s.tokens.toLocaleString() + ' tokens');
      put('docs', num(s.docs), s.docs.toLocaleString() + ' documents');
      put('bytes', size(s.bytes), s.bytes.toLocaleString() + ' bytes across ' + s.shards + ' shard(s)');
      put('licenses', licenses.length, licenses.join(', '));
      const when = (s.generated || '').slice(0, 10);
      const commit = s.index_commit ? 'waldo-index@' + s.index_commit : 'the public index';
      put('note', 'counted from ' + commit + (when ? ' on ' + when : '') +
        ' — every number verifiable, shard by shard');
    })
    .catch(() => {});
}

// Hero: cycle a glow across the W-A-L-D-O letters
const letters = document.querySelectorAll('h1.title .k');
if (letters.length && !window.matchMedia('(prefers-reduced-motion: reduce)').matches) {
  let i = 0;
  setInterval(() => {
    letters.forEach((l) => l.classList.remove('lit'));
    letters[i % letters.length].classList.add('lit');
    i++;
  }, 900);
}
